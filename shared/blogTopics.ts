// Export helper functions
export function getBlogBySlug(slug: string): BlogTopic | undefined {
  return blogTopics.find((blog) => blog.slug === slug);
}

export function getBlogsByCategory(category: string): BlogTopic[] {
  return blogTopics.filter((blog) => blog.category === category);
}

export function getAllCategories(): string[] {
  return Array.from(new Set(blogTopics.map((blog) => blog.category)));
}

export function searchBlogs(query: string): BlogTopic[] {
  const lowerQuery = query.toLowerCase();
  return blogTopics.filter(
    (blog) =>
      blog.title.toLowerCase().includes(lowerQuery) ||
      blog.description.toLowerCase().includes(lowerQuery) ||
      blog.keywords.some((kw) => kw.toLowerCase().includes(lowerQuery))
  );
}
